/*
a) O while testa a condição antes de executar o bloco. Se a condição começar falsa, o bloco nunca roda. O do-while executa o bloco pelo menos uma vez e só depois testa a condição.


b) 
O for é melhor quando você sabe quantas vezes o bloco deve ser executado.
O while é melhor quando você não sabe quantas vezes o bloco deve ser executado, mas quer testar a condição antes de executar o bloco.
O do-while é melhor quando você não sabe quantas vezes o bloco deve ser executado, mas quer garantir que o bloco seja executado pelo menos uma vez antes de testar a condição.


c) É um erro de lógica. O ponto-e-vírgula faz o laço ter um corpo vazio. Se a condição for verdadeira, o programa fica em um loop infinito, porque nada dentro do laço muda a condição, e o programa fica repetindo a verificação da condição infinitamente.
*/